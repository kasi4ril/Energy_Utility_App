"""Automated Shift and Monthly Executive Document & Report Formatter.

Converts telemetry data, fault logs, call-collated shift roll-calls, and audit findings
into standardized executive markdown reports for C-Suite and Department Heads.
"""

from __future__ import annotations

import datetime
from typing import Any, Dict, List


class ReportFormatter:
    """Formats structured operational shift and monthly reports."""

    @staticmethod
    def format_shift_handover_report(shift_data: Dict[str, Any]) -> str:
        """Compiles shift handover metrics into an executive-ready Markdown document."""
        shift_window = shift_data.get("shift_window", "08:00 - 16:00 Morning Shift")
        date_str = shift_data.get("date", datetime.date.today().isoformat())
        station = shift_data.get("station_name", "Generation Master Station / Central Dispatch")
        outgoing_op = shift_data.get("outgoing_operator", "N/A")
        incoming_op = shift_data.get("incoming_operator", "N/A")

        plants: List[Dict[str, Any]] = shift_data.get("plants_telemetry", [])
        active_faults: List[str] = shift_data.get("active_faults", [])
        safety_advisories: List[str] = shift_data.get("safety_advisories", [])

        lines = [
            f"# NESCO OPERATIONAL SHIFT HANDOVER REPORT",
            f"**Station:** {station}  ",
            f"**Shift Window:** {shift_window} | **Date:** {date_str}  ",
            f"**Outgoing Operator:** {outgoing_op} | **Incoming Operator:** {incoming_op}  ",
            "",
            "---",
            "",
            "## 1. Plant Generation & Hydrological Telemetry",
            "| Plant Name | State | MW Generated | Water Level (m) | Oil Pressure |",
            "| :--- | :--- | :--- | :--- | :--- |",
        ]

        total_mw = 0.0
        for p in plants:
            name = p.get("plant_name", "Plant")
            state = p.get("state", "IN_SERVICE")
            mw = float(p.get("mw_generated", 0.0))
            water = p.get("water_level_m", "N/A")
            oil = p.get("oil_pressure_bar", "N/A")
            total_mw += mw
            lines.append(f"| {name} | `{state}` | {mw:.2f} MW | {water} | {oil} bar |")

        lines.extend([
            "",
            f"**Total Generation Output:** `{total_mw:.2f} MW`",
            "",
            "## 2. Active Faults & Unresolved Trips",
        ])

        if active_faults:
            for fault in active_faults:
                lines.append(f"- [!] {fault}")
        else:
            lines.append("- *No outstanding fault conditions reported during shift window.*")

        lines.extend([
            "",
            "## 3. HSE & Safety Advisories",
        ])

        if safety_advisories:
            for adv in safety_advisories:
                lines.append(f"- [HSE] {adv}")
        else:
            lines.append("- *All feeder isolations and PTW permits strictly validated.*")

        lines.extend([
            "",
            "---",
            f"*Generated by NESCO Local AI Guardian (@ReportFormatter) at {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*",
        ])

        return "\n".join(lines)

